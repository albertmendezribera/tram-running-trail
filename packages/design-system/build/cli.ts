/**
 * pnpm tokens:build   → regenerate dist/
 * pnpm tokens:check   → fail if dist/ does not match tokens/ (used in CI)
 */
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildDesignSystem } from './build.ts';
import { formatDiagnostic } from './model.ts';

const pkgRoot = fileURLToPath(new URL('..', import.meta.url));
const tokensDir = join(pkgRoot, 'tokens');
const distDir = join(pkgRoot, 'dist');
const check = process.argv.includes('--check');

const t0 = performance.now();
const result = buildDesignSystem({
  read: (p) => {
    const full = join(tokensDir, p);
    return existsSync(full) ? readFileSync(full, 'utf8') : undefined;
  },
});
const ms = performance.now() - t0;

for (const w of result.diagnostics.warnings) console.warn(`⚠ tokens/${formatDiagnostic(w)}`);
for (const e of result.diagnostics.errors) console.error(`✖ tokens/${formatDiagnostic(e)}`);
if (result.diagnostics.errors.length > 0) {
  console.error(`\n${result.diagnostics.errors.length} error(s). dist/ was not touched.`);
  process.exit(1);
}

const expected = result.files;
const existing = existsSync(distDir) ? readdirSync(distDir) : [];

if (check) {
  const stale = Object.keys(expected).filter(
    (f) => !existsSync(join(distDir, f)) || readFileSync(join(distDir, f), 'utf8') !== expected[f],
  );
  const extra = existing.filter((f) => !(f in expected));
  if (stale.length || extra.length) {
    for (const f of stale) console.error(`✖ dist/${f} is out of date`);
    for (const f of extra) console.error(`✖ dist/${f} is not generated by the build`);
    console.error('\nRun `pnpm tokens:build` and commit packages/design-system/dist/.');
    process.exit(1);
  }
  console.log(`✔ dist/ matches tokens/ (${Object.keys(expected).length} files, built in ${ms.toFixed(1)} ms)`);
} else {
  mkdirSync(distDir, { recursive: true });
  for (const f of existing) if (!(f in expected)) rmSync(join(distDir, f));
  for (const [f, content] of Object.entries(expected)) writeFileSync(join(distDir, f), content);
  const set = result.set!;
  const count = (layer: string): number => [...set.base.values()].filter((d) => d.layer === layer).length;
  console.log(
    `✔ ${set.base.size} tokens (ref ${count('ref')}, sys ${count('sys')}, comp ${count('comp')}) → ` +
      `${Object.keys(expected).map((f) => `dist/${f}`).join(', ')} in ${ms.toFixed(1)} ms`,
  );
}
