// Turns a GPX track into an elevation profile: [km, elevation] every `step` metres.
// Keeps only distance and elevation: coordinates, times and sensor data are dropped.
// Usage: node scripts/gpx-to-profile.mjs <track.gpx> <out.ts> <exportName> [stepMetres]
import { readFileSync, writeFileSync } from 'node:fs';

const [input, output, name, stepArg] = process.argv.slice(2);
const step = Number(stepArg ?? 20);
const xml = readFileSync(input, 'utf8');

const points = [...xml.matchAll(/<trkpt\b([^>]*)>([\s\S]*?)<\/trkpt>/g)].map(([, attrs, body]) => ({
  lat: Number(/lat="([^"]+)"/.exec(attrs)?.[1]),
  lon: Number(/lon="([^"]+)"/.exec(attrs)?.[1]),
  ele: /<ele>([^<]+)<\/ele>/.exec(body)?.[1],
}));
if (points.length < 2 || points.some((p) => p.ele === undefined)) throw new Error('the track needs at least two points, all with elevation');

const R = 6371008.8;
const rad = (d) => (d * Math.PI) / 180;
const metres = (a, b) =>
  2 * R * Math.asin(Math.sqrt(Math.sin(rad(b.lat - a.lat) / 2) ** 2 + Math.cos(rad(a.lat)) * Math.cos(rad(b.lat)) * Math.sin(rad(b.lon - a.lon) / 2) ** 2));

const profile = [];
let distance = 0;
let next = 0;
points.forEach((p, i) => {
  if (i > 0) distance += metres(points[i - 1], p);
  if (distance >= next || i === points.length - 1) {
    profile.push([Number((distance / 1000).toFixed(3)), Number(Number(p.ele).toFixed(1))]);
    next = distance + step;
  }
});

writeFileSync(
  output,
  `// GENERATED by apps/web/scripts/gpx-to-profile.mjs. Real data: distance and elevation only.\n` +
    `export const ${name}: ReadonlyArray<readonly [number, number]> = ${JSON.stringify(profile)};\n`,
);
console.log(`${profile.length} points, ${(distance / 1000).toFixed(2)} km`);
